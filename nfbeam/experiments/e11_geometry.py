"""E11: obstacle geometry estimation instead of a known nominal geometry.

All earlier experiments assume the obstacle's nominal geometry is known and
only weigh a 3 x 3 grid of small perturbations around it.  E11 estimates it:

  stage 1  one-off echo scan (205 near-field focused beams, 0.1 ms each,
           about one 20 ms frame) fitted with a physical-optics front-face
           model -> centre, width, front-face distance and their covariance;
  stage 2  the link's existing online hypothesis posterior, with the 3 x 3
           hypotheses centred on the stage-1 estimate and spaced by its spread.
           An estimate that fails the acceptance test (fitted echo peak SNR
           < 15 dB or > 10 % unexplained echo energy) is discarded and the
           hypotheses fall back to the prior.

Echoes and the link are generated by the full-wave channel (``nfbeam.fullwave``)
for three obstacle materials, so the estimator's model is never the truth:

  metal      perfect conductor, E out of plane         (Gamma = -1)
  metal_te   perfect conductor, H out of plane         (Gamma = +1)
  lossy      impedance surface, power reflectivity 0.1  (human-body-like)
  absorber   impedance-matched surface                  (no specular echo)

Part A  estimation accuracy vs the Cramér–Rao bound, at three echo SNRs.
Part B  end-to-end cooperative link with the nominal geometry from
        known (previous assumption) / echo (stage 1 + 2) / prior (no estimate,
        hypotheses spread over the prior).
"""

from __future__ import annotations

import argparse
import json
import time

import numpy as np
import pandas as pd

from direct_network.core.physics import Scene
from nfbeam.fullwave import FullWaveChannel
from nfbeam.geometry_est import (PRIOR, PRIOR_DEPTH_M, EchoEstimator, hypothesis_scenes, measure,
                                 scan_beams)
from nfbeam.scenes import RESULTS, load_scenes, run_parallel, write_json

OUT = RESULTS / "e11"
PPW = 12
NOISE = 3e-4                                   # complex noise power of a 0.1 ms slot
TRUTHS = {"metal": ("tm", 1.0), "metal_te": ("te", 1.0), "lossy": ("absorber", 0.519),
          "absorber": ("absorber", 1.0)}
SNR_OFFSETS_DB = (-10.0, 0.0, 10.0)           # echo SNR relative to the nominal dwell
DRAWS = 8
LINK_TRUTHS = ("metal", "lossy", "absorber")
NOMINALS = ("known", "echo", "prior")
LINK_POLICIES = ("focus_bayes", "proposed_warm")
LINK_RUNS = 5


def true_theta(sc: Scene) -> np.ndarray:
    return np.array([sc.obstacle_x_m, sc.obstacle_width_m, sc.obstacle_z_m - sc.obstacle_depth_m / 2])


def prior_scene(sc: Scene) -> Scene:
    from dataclasses import replace
    x = np.mean(PRIOR["x_c"]); w = np.mean(PRIOR["width"]); z = np.mean(PRIOR["z_f"])
    return replace(sc, obstacle_x_m=float(x), obstacle_width_m=float(w),
                   obstacle_z_m=float(z + PRIOR_DEPTH_M / 2), obstacle_depth_m=PRIOR_DEPTH_M)


def prior_hypotheses(sc: Scene) -> list[Scene]:
    from nfbeam.channel import perturbed
    p = prior_scene(sc)
    sx = (PRIOR["x_c"][1] - PRIOR["x_c"][0]) / np.sqrt(12)
    sw = (PRIOR["width"][1] - PRIOR["width"][0]) / np.sqrt(12) / p.obstacle_width_m
    return [perturbed(p, dx_m=dx, width_scale=ws) for dx in (-sx, 0, sx) for ws in (1 - sw, 1, 1 + sw)]


# --------------------------------------------------------------------- part A
def estimation_work(item) -> list[dict]:
    sid, sc, truth = item
    bc, beta = TRUTHS[truth]
    fw = FullWaveChannel(sc, bc, PPW, echo=True, beta=beta)
    W = scan_beams(fw)
    th = true_theta(sc)
    rows = []
    y_clean = fw.pitch * np.einsum("bi,ij,bj->b", W, fw.H_echo, W)
    for off in SNR_OFFSETS_DB:
        noise = NOISE * 10 ** (-off / 10)
        est = EchoEstimator(fw, W, noise)
        m_true = est.model(*th)
        g_true = est._fit_gain(np.abs(y_clean), m_true)[0]
        crb = np.sqrt(np.maximum(np.diag(est.covariance(th, g_true)), 0)) if g_true > 0 else np.full(3, np.nan)
        for d in range(DRAWS):
            rng = np.random.default_rng(1_000_000 * sid + 1000 * int(off + 50) + d + 100 * list(TRUTHS).index(truth))
            t0 = time.perf_counter()
            e = est.fit(measure(fw.H_echo, W, fw.pitch, noise, rng))
            rows.append({"scene_id": sid, "truth": truth, "snr_offset_db": off, "draw": d,
                         "peak_snr_db": float(10 * np.log10(np.max(np.abs(y_clean)) ** 2 / noise)),
                         "x_c_true": th[0], "width_true": th[1], "z_f_true": th[2],
                         "x_c": e.x_c, "width": e.width, "z_f": e.z_f, "gamma": e.gamma,
                         "fit_peak_snr_db": e.peak_snr_db, "rel_residual": e.rel_residual, "valid": e.valid,
                         "std_x_c": e.std[0], "std_width": e.std[1], "std_z_f": e.std[2],
                         "crb_x_c": crb[0], "crb_width": crb[1], "crb_z_f": crb[2],
                         "fit_s": time.perf_counter() - t0})
    return rows


def estimation_summary(f: pd.DataFrame) -> list[dict]:
    f = f.copy()
    f["err_x_c"] = f.x_c - f.x_c_true
    f["err_width"] = f.width - f.width_true
    f["err_z_f"] = f.z_f - f.z_f_true
    f["err_left"] = (f.x_c - f.width / 2) - (f.x_c_true - f.width_true / 2)
    f["err_right"] = (f.x_c + f.width / 2) - (f.x_c_true + f.width_true / 2)
    out = []
    for (truth, off), g in f.groupby(["truth", "snr_offset_db"], sort=False):
        row = {"truth": truth, "snr_offset_db": off, "estimates": len(g),
               "peak_snr_db_median": float(g.peak_snr_db.median())}
        for p in ("x_c", "width", "z_f"):
            e = 1000 * g[f"err_{p}"]
            row[f"{p}_rmse_mm"] = float(np.sqrt(np.mean(e ** 2)))
            row[f"{p}_median_abs_mm"] = float(np.median(np.abs(e)))
            row[f"{p}_bias_mm"] = float(np.mean(e))
            row[f"{p}_crb_mm_median"] = float(1000 * g[f"crb_{p}"].median())
        edge = 1000 * np.abs(np.r_[g.err_left, g.err_right])
        row["edge_median_abs_mm"] = float(np.median(edge))
        row["edge_p90_abs_mm"] = float(np.quantile(edge, .9))
        row["edge_gt_5mm_pct"] = float(100 * np.mean(edge > 5))
        row["gamma_median"] = float(g.gamma.median())
        row["accepted_pct"] = float(100 * g.valid.mean())
        acc = g[g.valid]
        if len(acc):
            ea = 1000 * np.abs(np.r_[acc.err_left, acc.err_right])
            row["accepted_edge_median_abs_mm"] = float(np.median(ea))
            row["accepted_edge_p90_abs_mm"] = float(np.quantile(ea, .9))
            row["accepted_edge_gt_5mm_pct"] = float(100 * np.mean(ea > 5))
        rej = g[~g.valid]
        if len(rej):
            row["rejected_edge_median_abs_mm"] = float(np.median(1000 * np.abs(np.r_[rej.err_left, rej.err_right])))
        row["fit_s_mean"] = float(g.fit_s.mean())
        out.append(row)
    return out


# --------------------------------------------------------------------- part B
def link_work(item) -> list[dict]:
    from nfbeam.link import Condition, RunRandom, SceneContext, run_coop, trajectory
    sid, sc, truth_name, runs = item
    bc, beta = TRUTHS[truth_name]
    fw = FullWaveChannel(sc, bc, PPW, echo=True, beta=beta)
    W = scan_beams(fw)
    est = EchoEstimator(fw, W, NOISE).fit(measure(fw.H_echo, W, fw.pitch, NOISE, np.random.default_rng(91_000 + sid)))
    cond = Condition("matched")
    base = SceneContext(sid, sc, cond, seed=7000 + sid, need_legacy=False)
    est_scene = est.scene(sc)
    # Rejected echo estimates fall back to the prior hypotheses.
    echo_setup = (est_scene, hypothesis_scenes(est_scene, est)) if est.valid else (prior_scene(sc), prior_hypotheses(sc))
    setups = {"known": (sc, None), "echo": echo_setup,
              "prior": (prior_scene(sc), prior_hypotheses(sc))}
    rows = []
    for nominal in NOMINALS:
        scene_n, hyps = setups[nominal]
        ctx = SceneContext(sid, scene_n, cond, seed=7000 + sid, need_legacy=False,
                           data_noise=base.data_noise, truth=fw, hyp_scenes=hyps)
        pols = LINK_POLICIES + (("oracle",) if nominal == "known" else ())
        for run in range(runs):
            path = trajectory(run)
            rr = RunRandom.draw(len(path), 181100 + 100 * sid + run, cond.loss)
            for pol in pols:
                for r in run_coop(ctx, pol, path, rr):
                    r.update(truth=truth_name, nominal=nominal, scene_id=sid, run=run,
                             policy=pol if pol == "oracle" else f"{pol}@{nominal}",
                             est_x_c=est.x_c, est_width=est.width, est_z_f=est.z_f,
                             est_valid=est.valid)
                    rows.append(r)
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--parts", nargs="*", default=["estimation", "link"])
    ap.add_argument("--runs", type=int, default=LINK_RUNS)
    ap.add_argument("--workers", type=int, default=None)
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    scenes = load_scenes("test")
    path = OUT / "summary.json"
    summary = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    summary["setup"] = {"scan_beams": 205, "dwell_ms": 0.1, "noise_power": NOISE, "prior": PRIOR,
                        "prior_depth_m": PRIOR_DEPTH_M, "truths": TRUTHS, "points_per_wavelength": PPW}

    if "estimation" in args.parts:
        items = [(sid, sc, t) for t in TRUTHS for sid, sc in scenes]
        f = pd.DataFrame([r for c in run_parallel(estimation_work, items, args.workers) for r in c])
        f.to_csv(OUT / "estimates.csv", index=False, float_format="%.7g")
        summary["estimation"] = estimation_summary(f)
        write_json(path, summary)
        print(pd.DataFrame(summary["estimation"]).round(3).to_string(index=False))

    if "link" in args.parts:
        from nfbeam.metrics import add_columns, paired_change, region_summary
        items = [(sid, sc, t, args.runs) for t in LINK_TRUTHS for sid, sc in scenes]
        frames = pd.DataFrame([r for c in run_parallel(link_work, items, args.workers) for r in c])
        frames.to_csv(OUT / "link_frames.csv.gz", index=False, float_format="%.7g")
        fr = add_columns(frames)
        pols = sorted(fr.policy.unique())
        summary["link"] = {
            "runs_per_scene": args.runs,
            "metrics": region_summary(fr, ["truth", "policy"]),
            "vs_known": [r for p in LINK_POLICIES for n in ("echo", "prior")
                         for r in paired_change(fr, ["truth"], f"{p}@{n}", f"{p}@known")],
            "echo_vs_prior": [r for p in LINK_POLICIES
                              for r in paired_change(fr, ["truth"], f"{p}@echo", f"{p}@prior")],
            "vs_oracle": [r for p in pols if p != "oracle"
                          for r in paired_change(fr, ["truth"], p, "oracle")]}
        write_json(path, summary)
        m = pd.DataFrame(summary["link"]["metrics"])
        print(m[m.region == "deep"][["truth", "policy", "se_mean", "low_rate_pct", "mae_mm",
                                     "lock_lost_pct", "scan_pct"]].round(3).to_string(index=False))
        for key in ("vs_known", "echo_vs_prior"):
            c = pd.DataFrame(summary["link"][key])
            print(c[c.region == "deep"].round(2).to_string(index=False))


if __name__ == "__main__":
    main()
